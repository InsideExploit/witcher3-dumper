// state shared by the classes.hpp generation helpers
struct hpp_ctx
{
	std::unordered_map<std::string, const class_info *> classes;
	std::unordered_map<std::string, const enum_info *> enums;
	std::unordered_set<std::string> bitfields;
	std::unordered_set<std::string> scripted; // classes with their own script variables
	std::unordered_set<std::string> objects;  // ISerializable descendants, written as "class"
	std::unordered_map<std::string, uint32_t> align; // C++ alignment of every emitted type (and "X::ScriptData")
	std::unordered_map<std::string, uint32_t> size;  // C++ sizeof of every emitted ScriptData
	std::unordered_set<std::string> exact; // emitted with sizeof == reflected size
	std::unordered_map<std::string, uint32_t> forced; // alignof under #pragma pack(1) of every emitted type
	std::unordered_map<std::string, uint32_t> cap;    // largest alignment every by-value embedding of a type allows
	std::unordered_set<std::string> done;
	std::string out;
	std::string asserts;
};

static const char *keyword(const hpp_ctx& g, const std::string& name)
{
	return g.objects.count(name) ? "class" : "struct";
}

struct fundamental
{
	const char *cpp;
	uint32_t size;
	bool by_value;
};

static const fundamental *find_fundamental(const std::string& t)
{
	static const std::unordered_map<std::string, fundamental> m = {
		{ "Bool", { "bool", 1, true } }, { "Int8", { "int8_t", 1, true } }, { "Uint8", { "uint8_t", 1, true } }, { "Int16", { "int16_t", 2, true } },
		{ "Uint16", { "uint16_t", 2, true } }, { "Int32", { "int32_t", 4, true } }, { "Uint32", { "uint32_t", 4, true } }, { "Int64", { "int64_t", 8, true } },
		{ "Uint64", { "uint64_t", 8, true } }, { "Float", { "float", 4, true } }, { "Double", { "double", 8, true } }, { "CName", { "struct CName", 4, true } },
		{ "String", { "struct String", 12, false } },
	};

	auto it = m.find(t);
	return it == m.end() ? nullptr : &it->second;
}

static uint32_t read_num(const std::string& t, size_t& i)
{
	uint32_t n = 0;
	while (i < t.size() && t[i] >= '0' && t[i] <= '9')
	{
		n = n * 10 + (t[i++] - '0');
	}

	if (i < t.size() && t[i] == ',')
	{
		++i;
	}

	return n;
}

// C++ spelling of the reflected type name starting at t[i], advancing i past it. Grammar:
// array:<mc>,<pool>,T  static:<n>,T  map:<mc>,<pool>,K,V  handle:T  soft:T  ptr:T  or a plain name.
// Class and simple types are written as "struct X" and enums as "enum X", so a member function
// with the same name as a type cannot hide it.
static std::string spell(const hpp_ctx& g, const std::string& t, size_t& i)
{
	auto take = [&](const char *p)
	{
		size_t n = strlen(p);
		if (t.compare(i, n, p) != 0)
			return false;

		i += n;
		return true;
	};

	if (take("array:"))
	{
		read_num(t, i);
		read_num(t, i);
		return "TDynArray<" + spell(g, t, i) + ">";
	}

	if (take("static:"))
	{
		uint32_t n = read_num(t, i);
		return "TStaticArray<" + spell(g, t, i) + ", " + std::to_string(n) + ">";
	}

	if (take("map:"))
	{
		read_num(t, i);
		read_num(t, i);
		std::string k = spell(g, t, i);
		if (i < t.size() && t[i] == ',')
		{
			++i;
		}

		return "THashMap<" + k + ", " + spell(g, t, i) + ">";
	}

	if (take("handle:"))
		return "THandle<" + spell(g, t, i) + ">";

	if (take("soft:"))
		return "TSoftHandle<" + spell(g, t, i) + ">";

	if (take("ptr:"))
		return spell(g, t, i) + "*";

	size_t end = t.find(',', i);
	if (end == std::string::npos)
	{
		end = t.size();
	}

	std::string name = t.substr(i, end - i);
	i = end;

	if (const fundamental *f = find_fundamental(name))
		return f->cpp;

	if (g.enums.count(name) || g.bitfields.count(name))
		return "enum " + ident(name);

	return std::string(keyword(g, name)) + " " + ident(name);
}

static std::string spell(const hpp_ctx& g, const std::string& t)
{
	size_t i = 0;
	return spell(g, t, i);
}

// Field type when its layout is known and matches the reflected size, else empty (emitted as bytes).
static std::string field_type(const hpp_ctx& g, const std::string& t, uint32_t size)
{
	uint32_t expect = 0;
	if (const fundamental *f = find_fundamental(t))
	{
		expect = f->size;
	}
	else if (g.enums.count(t))
	{
		expect = g.enums.at(t)->size;
	}
	else if (g.classes.count(t))
	{
		expect = g.classes.at(t)->size;
	}
	else if (t.rfind("ptr:", 0) == 0 || t.rfind("handle:", 0) == 0)
	{
		expect = 8;
	}
	else if (t.rfind("array:", 0) == 0)
	{
		expect = 12;
	}

	return expect && expect == size ? spell(g, t) : "";
}

// Alignment C++ gives a field written with field_type (byte arrays align to 1). TDynArray and String
// are declared under pack(4), like the engine's 12-byte containers.
static uint32_t field_align(const hpp_ctx& g, const std::string& t, bool typed)
{
	if (!typed)
		return 1;

	if (t == "String" || t.rfind("array:", 0) == 0)
		return 4;

	if (const fundamental *f = find_fundamental(t))
		return f->size;

	if (t.rfind("ptr:", 0) == 0 || t.rfind("handle:", 0) == 0)
		return 8;

	if (g.enums.count(t))
		return g.enums.at(t)->size;

	auto a = g.align.find(t);
	return a == g.align.end() ? 1 : a->second;
}

// Parameter as UE style SDKs write it: small values by value, everything else by const reference,
// script "out" parameters by reference.
static std::string param_decl(const hpp_ctx& g, const prop_info& p)
{
	std::string t = spell(g, p.type);
	const fundamental *f = find_fundamental(p.type);
	bool by_val = (f && f->by_value) || g.enums.count(p.type) || g.bitfields.count(p.type) || p.type.rfind("ptr:", 0) == 0;

	std::string s;
	if (p.flags & PF_Out)
	{
		s = t + "& ";
	}
	else if (by_val)
	{
		s = t + " ";
	}
	else
	{
		s = "const " + t + "& ";
	}

	s += ident(p.name);
	if (p.flags & PF_Optional)
	{
		s += " /* Optional */";
	}

	return s;
}

// "bool OnAnimEvent(struct CName animEventName, ...); // event, rva 0x..."
static std::string func_decl(const hpp_ctx& g, const func_info& f, const std::string& name, bool is_static)
{
	std::string s = is_static ? "static " : "";
	s += f.ret == "void" ? std::string("void") : spell(g, f.ret);
	s += " " + name + "(";
	for (size_t i = 0; i < f.params.size(); ++i)
	{
		if (i)
		{
			s += ", ";
		}

		s += param_decl(g, f.params[i]);
	}

	s += ");";

	static const std::pair<uint32_t, const char *> words[] = {
		{ FF_Private, "Private" }, { FF_Protected, "Protected" }, { FF_Native, "Native" }, { FF_Final, "Final" }, { FF_Event, "Event" },
		{ FF_Latent, "Latent" }, { FF_Entry, "Entry" }, { FF_Exec, "Exec" }, { FF_Timer, "Timer" }, { FF_StoryScene, "StoryScene" },
		{ FF_Quest, "Quest" }, { FF_Cleanup, "Cleanup" }, { FF_Reward, "Reward" },
	};

	std::string notes;
	for (auto& w : words)
	{
		if (f.flags & w.first)
		{
			notes += notes.empty() ? w.second : std::string(", ") + w.second;
		}
	}

	if (f.flags & FF_Native)
	{
		notes += f.rva ? ", RVA " + hex(f.rva) : std::string(", Unbound");
	}

	if (!notes.empty())
	{
		s += " // " + notes;
	}

	return s;
}

// one line of a generated struct body
struct field_row
{
	std::string text;   // declaration and comment, without indentation
	std::string name;   // member name, empty for pads and comments
	uint32_t offset = 0;
	uint32_t size = 0;
	uint32_t align = 1; // natural alignment, 0 for comment lines
	uint32_t forced = 1; // alignment that survives #pragma pack (from alignas inside the type)
};

// Rows for props placed from 'start'; pads fill the gaps. Overlapping props become comment lines.
static void make_rows(const hpp_ctx& g, const std::vector<const prop_info *>& props, uint32_t start, const char *sign, std::unordered_set<std::string>& used, std::vector<field_row>& rows, bool& exact)
{
	uint32_t cur = start;
	for (const prop_info *pr : props)
	{
		if (pr->offset < cur || !pr->size)
		{
			rows.push_back({ fmt("// %s0x%04X (0x%04X) %s: Overlaps the previous field", sign, pr->offset, pr->size, pr->name.c_str()), "", pr->offset, 0, 0 });
			exact = false;
			continue;
		}

		if (pr->offset > cur)
		{
			rows.push_back({ fmt("uint8_t pad_%04X[0x%X]; // %s0x%04X (0x%04X)", cur, pr->offset - cur, sign, cur, pr->offset - cur), "", cur, pr->offset - cur, 1 });
		}

		std::string n = ident(pr->name);
		for (int i = 2; used.count(n); ++i)
		{
			n = ident(pr->name) + "_" + std::to_string(i);
		}

		used.insert(n);

		// a byte array keeps the RED type name, it is the only place it survives
		std::string t = field_type(g, pr->type, pr->size);
		std::string text;
		if (t.empty())
		{
			text = fmt("uint8_t %s[0x%X]; // %s0x%04X (0x%04X) %s", n.c_str(), pr->size, sign, pr->offset, pr->size, pr->type.c_str());
		}
		else
		{
			text = fmt("%s %s; // %s0x%04X (0x%04X)", t.c_str(), n.c_str(), sign, pr->offset, pr->size);
		}

		uint32_t forced = 1;
		auto f = g.forced.find(pr->type);
		if (!t.empty() && f != g.forced.end())
		{
			forced = f->second;
		}

		rows.push_back({ text, n, pr->offset, pr->size, field_align(g, pr->type, !t.empty()), forced });
		cur = pr->offset + pr->size;
	}
}

struct layout
{
	bool ok = true;       // every row lands on its offset without packing
	uint32_t align = 1;   // natural alignof
	uint32_t forced = 1;  // alignof under #pragma pack(1)
	bool pack = false;
	uint32_t alignas_ = 0; // alignas to emit, 0 for none
	uint32_t final = 1;   // resulting alignof
};

static layout measure(const std::vector<field_row>& rows, uint32_t start, uint32_t base_align, uint32_t base_forced)
{
	layout l;
	l.align = base_align;
	l.forced = base_forced;
	uint32_t cur = start;
	for (const field_row& r : rows)
	{
		if (!r.align)
			continue;

		uint32_t at = (cur + r.align - 1) / r.align * r.align;
		if (at != r.offset)
		{
			l.ok = false;
		}

		cur = r.offset + r.size;
		l.align = std::max(l.align, r.align);
		l.forced = std::max(l.forced, r.forced);
	}

	return l;
}

// Packs only when C++ would move a field or grow the size, and adds alignas only when the reflected
// alignment is above what C++ already gives and every place that embeds the type allows it (cap).
static void choose(layout& l, uint32_t want, uint32_t cap, uint32_t total)
{
	want = std::min(want, cap);
	for (int pass = 0; pass < 2; ++pass)
	{
		l.pack = pass == 1 || !l.ok || l.align > cap;
		uint32_t base = l.pack ? l.forced : l.align;
		l.alignas_ = want > base && total % want == 0 ? want : 0;
		l.final = l.alignas_ ? l.alignas_ : base;
		if (l.pack || total % l.final == 0)
			return;
	}
}

static void class_body(hpp_ctx& g, const class_info *k)
{
	std::string name = ident(k->name);
	const class_info *parent = nullptr;
	auto p = g.classes.find(k->parent);
	if (p != g.classes.end())
	{
		parent = p->second;
	}

	bool exact = true;
	bool inherit = parent && parent->size <= k->size && g.exact.count(parent->name);
	uint32_t start = inherit ? parent->size : 0;
	uint32_t base_align = inherit ? g.align[parent->name] : 1;
	uint32_t base_forced = inherit ? g.forced[parent->name] : 1;

	std::vector<const prop_info *> native;
	std::vector<const prop_info *> script;
	for (const prop_info& pr : k->props)
	{
		if (pr.flags & PF_Scripted)
		{
			script.push_back(&pr);
		}
		else
		{
			native.push_back(&pr);
		}
	}

	std::unordered_set<std::string> used;
	std::vector<field_row> rows;
	make_rows(g, native, start, "", used, rows, exact);

	uint32_t end = start;
	for (const field_row& r : rows)
	{
		end = std::max(end, r.offset + r.size);
	}

	if (k->size > end)
	{
		rows.push_back({ fmt("uint8_t pad_%04X[0x%X]; // 0x%04X (0x%04X)", end, k->size - end, end, k->size - end), "", end, k->size - end, 1 });
	}
	else if (k->size < end)
	{
		exact = false;
	}

	// the cap keeps the alignment at what every embedding allows
	// (Color reports 4 but sits at +0x21 in SDynamicDecalMaterialInfo)
	layout l = measure(rows, start, base_align, base_forced);
	auto cap = g.cap.find(k->name);
	choose(l, k->align, cap == g.cap.end() ? 16 : cap->second, k->size);
	bool pack = l.pack;
	uint32_t final_align = l.final;

	const char *kw = keyword(g, k->name);
	g.out += "// " + std::string(kw == std::string("class") ? "Class " : "Struct ") + k->name + "\n";
	g.out += fmt("// 0x%04X (0x%04X - 0x%04X)\n", k->size - start, k->size, start);
	if (pack)
	{
		g.out += "#pragma pack(push, 0x1)\n";
	}

	std::string decl = std::string(kw) + " ";
	if (l.alignas_)
	{
		decl += fmt("alignas(0x%02X) ", l.alignas_);
	}

	decl += name;
	if (inherit)
	{
		decl += " : public " + ident(parent->name);
	}

	g.out += decl + "\n{\n";
	if (kw == std::string("class"))
	{
		g.out += "public:\n";
	}

	if (parent && !inherit)
	{
		g.out += "\t// Parent " + parent->name + " has no exact layout, not inherited\n";
		exact = false;
	}

	for (const field_row& r : rows)
	{
		g.out += "\t" + r.text + "\n";
	}

	// a method may not reuse a field name or the class name
	used.insert(name);

	// Script variables of IScriptable objects are not inside the object: the VM keeps them in a separate
	// buffer whose pointer is at IScriptable+0x20 (OpObjectVar: base = *(obj + 0x20) + offset). They are
	// laid out in a nested ScriptData struct that extends the nearest ancestor's one.
	std::vector<field_row> srows;
	std::string sname = k->name + "::ScriptData";
	if (!script.empty())
	{
		const class_info *base = nullptr;
		for (auto a = g.classes.find(k->parent); a != g.classes.end(); a = g.classes.find(a->second->parent))
		{
			if (g.scripted.count(a->second->name))
			{
				base = a->second;
				break;
			}
		}

		// when the ancestor's ScriptData is larger in C++ than where this class starts, flatten instead
		uint32_t sstart = base ? g.size[base->name + "::ScriptData"] : 0;
		if (base && script.front()->offset < sstart)
		{
			std::vector<const prop_info *> all;
			for (auto a = g.classes.find(k->parent); a != g.classes.end(); a = g.classes.find(a->second->parent))
			{
				for (const prop_info& pr : a->second->props)
				{
					if (pr.flags & PF_Scripted)
					{
						all.push_back(&pr);
					}
				}
			}

			std::sort(all.begin(), all.end(), [](const prop_info *x, const prop_info *y)
			{
				return x->offset < y->offset;
			});

			all.insert(all.end(), script.begin(), script.end());
			script = all;
			base = nullptr;
			sstart = 0;
		}

		std::unordered_set<std::string> vars;
		bool sexact = true;
		make_rows(g, script, sstart, "+", vars, srows, sexact);

		std::string bname = base ? base->name + "::ScriptData" : "";
		layout sl = measure(srows, sstart, base ? g.align[bname] : 1, base ? g.forced[bname] : 1);
		uint32_t send = sstart;
		for (const field_row& r : srows)
		{
			send = std::max(send, r.offset + r.size);
		}

		// the buffer is heap memory, so 16 is the cap; no alignas is ever needed
		choose(sl, 1, 16, (send + sl.align - 1) / sl.align * sl.align);
		bool sok = !sl.pack;
		g.align[sname] = sl.final;
		g.forced[sname] = sl.forced;
		g.size[sname] = (send + sl.final - 1) / sl.final * sl.final;

		if (!rows.empty())
		{
			g.out += "\n";
		}

		if (!sok)
		{
			g.out += "#pragma pack(push, 0x1)\n";
		}

		g.out += base ? "\tstruct ScriptData : public " + ident(base->name) + "::ScriptData\n\t{\n" : std::string("\tstruct ScriptData\n\t{\n");
		for (const field_row& r : srows)
		{
			g.out += "\t\t" + r.text + "\n";
		}

		g.out += "\t};\n";
		if (!sok)
		{
			g.out += "#pragma pack(pop)\n";
		}

		std::string acc = used.count("script") ? "script_vars" : "script";
		used.insert(acc);
		g.out += "\n\tScriptData *" + acc + "()\n\t{\n\t\treturn *(ScriptData **)((uint8_t *)this + 0x20);\n\t}\n";
	}

	std::string funcs;
	for (const func_info& f : k->funcs)
	{
		std::string n = ident(f.name);
		if (used.count(n))
		{
			n += "_func";
		}

		used.insert(n);
		funcs += "\t" + func_decl(g, f, n, false) + "\n";
	}

	if (!funcs.empty())
	{
		g.out += "\n\t// Functions\n" + funcs;
	}

	g.out += "};\n";
	if (pack)
	{
		g.out += "#pragma pack(pop)\n";
	}

	g.out += "\n";
	g.align[k->name] = final_align;
	g.forced[k->name] = l.alignas_ ? std::max(l.alignas_, l.forced) : l.forced;

	if (!exact || !k->size)
		return;

	g.exact.insert(k->name);
	g.asserts += "// " + std::string(kw == std::string("class") ? "Class " : "Struct ") + k->name + "\n";
	g.asserts += fmt("static_assert(alignof(%s) == 0x%06X, \"Wrong alignment on %s\");\n", name.c_str(), final_align, k->name.c_str());
	g.asserts += fmt("static_assert(sizeof(%s) == 0x%06X, \"Wrong size on %s\");\n", name.c_str(), k->size, k->name.c_str());
	for (const field_row& r : rows)
	{
		if (!r.name.empty())
		{
			g.asserts += fmt("static_assert(offsetof(%s, %s) == 0x%06X, \"Member '%s::%s' has a wrong offset!\");\n", name.c_str(), r.name.c_str(), r.offset, k->name.c_str(), r.name.c_str());
		}
	}

	for (const field_row& r : srows)
	{
		if (!r.name.empty())
		{
			g.asserts += fmt("static_assert(offsetof(%s::ScriptData, %s) == 0x%06X, \"Member '%s::ScriptData::%s' has a wrong offset!\");\n", name.c_str(), r.name.c_str(), r.offset, k->name.c_str(), r.name.c_str());
		}
	}

	g.asserts += "\n";
}

// parents and by-value members first, so every struct is complete where it is used
static void emit_class(hpp_ctx& g, const class_info *k)
{
	if (g.done.count(k->name))
		return;

	g.done.insert(k->name);

	auto p = g.classes.find(k->parent);
	if (p != g.classes.end())
	{
		emit_class(g, p->second);
	}

	for (const prop_info& pr : k->props)
	{
		if (pr.kind != RT_Class)
			continue;

		auto d = g.classes.find(pr.type);
		if (d != g.classes.end())
		{
			emit_class(g, d->second);
		}
	}

	class_body(g, k);
}

void writer::classes_hpp(const std::wstring& dir)
{
	auto& c = collector::get();
	hpp_ctx g;
	for (const class_info& k : c.classes)
	{
		g.classes[k.name] = &k;
	}

	for (const enum_info& e : c.enums)
	{
		g.enums[e.name] = &e;
	}

	for (const bitfield_info& b : c.bitfields)
	{
		g.bitfields.insert(b.name);
	}

	for (const class_info& k : c.classes)
	{
		for (const prop_info& p : k.props)
		{
			if (p.flags & PF_Scripted)
			{
				g.scripted.insert(k.name);
			}
		}

		for (auto a = g.classes.find(k.name); a != g.classes.end(); a = g.classes.find(a->second->parent))
		{
			if (a->second->name == "ISerializable")
			{
				g.objects.insert(k.name);
				break;
			}
		}
	}

	// Alignment caps: a type embedded by value at offset o inside S can be at most as aligned as
	// min(cap[S], lowest set bit of o); a base class is capped by its derived classes. Script
	// variables sit in a heap buffer (cap 16). Iterated to a fixed point.
	for (const class_info& k : c.classes)
	{
		g.cap[k.name] = 16;
	}

	for (bool changed = true; changed;)
	{
		changed = false;
		auto lower = [&](const std::string& t, uint32_t v)
		{
			auto it = g.cap.find(t);
			if (it != g.cap.end() && v < it->second)
			{
				it->second = v;
				changed = true;
			}
		};

		for (const class_info& k : c.classes)
		{
			uint32_t self = g.cap[k.name];
			lower(k.parent, self);
			for (const prop_info& p : k.props)
			{
				if (p.kind != RT_Class)
					continue;

				uint32_t outer = (p.flags & PF_Scripted) ? 16 : self;
				uint32_t low = p.offset ? (p.offset & (0u - p.offset)) : 16;
				lower(p.type, std::min(outer, low));
			}
		}
	}

	// every other plain type name used by a field or a signature (EngineTime, Vector...) gets a forward declaration
	std::unordered_set<std::string> simple;
	auto scan = [&](const std::string& t)
	{
		size_t i = 0;
		while (i < t.size())
		{
			size_t e = t.find_first_of(":,", i);
			if (e == std::string::npos)
			{
				e = t.size();
			}

			std::string w = t.substr(i, e - i);
			bool prefix = e < t.size() && t[e] == ':';
			bool num = !w.empty() && w[0] >= '0' && w[0] <= '9';
			if (!w.empty() && !prefix && !num && !find_fundamental(w) && !g.classes.count(w) && !g.enums.count(w) && !g.bitfields.count(w))
			{
				simple.insert(w);
			}

			i = e + 1;
		}
	};

	auto scan_func = [&](const func_info& f)
	{
		scan(f.ret);
		for (const prop_info& p : f.params)
		{
			scan(p.type);
		}
	};

	for (const class_info& k : c.classes)
	{
		for (const prop_info& p : k.props)
		{
			scan(p.type);
		}

		for (const func_info& f : k.funcs)
		{
			scan_func(f);
		}
	}

	for (const func_info& f : c.globals)
	{
		scan_func(f);
	}

	simple.erase("void");

	g.out = "#pragma once\n\n" + header_comment("Classes.hpp",
		"Field comments are offset (size). Script variables of IScriptable objects live in a separate buffer,\n"
		"reached through script() and the nested ScriptData struct. Functions are declarations only; natives\n"
		"carry their RVA in the trailing comment. Global script functions are static members of Globals.\n"
		"Layout checks are in Asserts.hpp.");
	g.out += "#include <cstdint>\n#include \"Enums.hpp\"\n\n";
	g.out += "struct CName\n{\n\tuint32_t index;\n};\n\n";
	g.out += "// The engine's 12-byte containers\n#pragma pack(push, 0x4)\n";
	g.out += "struct String\n{\n\tchar *data;\n\tuint32_t size;\n};\n\n";
	g.out += "template <class T>\nstruct TDynArray\n{\n\tT *data;\n\tuint32_t size;\n};\n#pragma pack(pop)\n\n";
	g.out += "template <class T>\nstruct THandle\n{\n\tvoid *block;\n};\n\n";
	g.out += "// Layouts not dumped, used in signatures only\ntemplate <class T>\nstruct TSoftHandle;\n\n";
	g.out += "template <class K, class V>\nstruct THashMap;\n\ntemplate <class T, uint32_t N>\nstruct TStaticArray;\n\n";

	for (const std::string& s : simple)
	{
		g.out += "struct " + ident(s) + ";\n";
	}

	for (const class_info& k : c.classes)
	{
		g.out += std::string(keyword(g, k.name)) + " " + ident(k.name) + ";\n";
	}

	g.out += "\n";
	for (const class_info& k : c.classes)
	{
		emit_class(g, &k);
	}

	g.out += "// Global Script Functions\nstruct Globals\n{\n";
	for (const func_info& f : c.globals)
	{
		g.out += "\t" + func_decl(g, f, ident(f.name), true) + "\n";
	}

	g.out += "};\n";
	save(dir + L"\\Classes.hpp", g.out);

	std::string a = "#pragma once\n\n" + header_comment("Asserts.hpp", "Size, alignment and member offset checks for Classes.hpp.\nInclude it in one translation unit.");
	a += "#include <cstddef>\n#include \"Classes.hpp\"\n\n" + g.asserts;
	save(dir + L"\\Asserts.hpp", a);
}

void writer::enums_hpp(const std::wstring& path)
{
	auto& c = collector::get();
	std::string s = "#pragma once\n\n" + header_comment("Enums.hpp", "Every reflected enum and bitfield.") + "#include <cstdint>\n\n";

	for (const enum_info& e : c.enums)
	{
		const char *base = e.size == 1 ? "int8_t" : e.size == 2 ? "int16_t" : e.size == 8 ? "int64_t" : "int32_t";
		s += fmt("// Enum %s | Size 0x%X%s\n", e.name.c_str(), e.size, e.scripted ? " | Scripted" : "");
		s += "enum class " + ident(e.name) + " : " + base + "\n{\n";
		for (auto& v : e.values)
		{
			s += fmt("\t%s = %d,\n", ident(v.first).c_str(), v.second);
		}

		s += "};\n\n";
	}

	for (const bitfield_info& b : c.bitfields)
	{
		const char *base = b.size == 1 ? "uint8_t" : b.size == 2 ? "uint16_t" : "uint32_t";
		s += fmt("// BitField %s | Size 0x%X\n", b.name.c_str(), b.size);
		s += "enum class " + ident(b.name) + " : " + base + "\n{\n";
		for (auto& v : b.bits)
		{
			s += fmt("\t%s = 0x%X,\n", ident(v.first).c_str(), 1u << v.second);
		}

		s += "};\n\n";
	}

	save(path, s);
}

// "IntRange<0,63>" -> "[0, 63]", "FloatRange<1,1000,100>" -> "[0.01, 10]", "Always" -> ""
static std::string range(const std::string& v)
{
	if (v.empty() || v == "Always")
		return "";

	bool is_int = v.rfind("IntRange<", 0) == 0;
	bool is_float = v.rfind("FloatRange<", 0) == 0;
	if (!is_int && !is_float)
		return v;

	double n[3] = { 0, 0, 1 };
	int count = sscanf_s(v.c_str() + v.find('<') + 1, "%lf,%lf,%lf", &n[0], &n[1], &n[2]);
	if (count < 2)
		return v;

	if (is_float && count == 3 && n[2] != 0)
	{
		n[0] /= n[2];
		n[1] /= n[2];
	}

	if (is_int)
		return fmt("[%lld, %lld]", (long long)n[0], (long long)n[1]);

	return fmt("[%g, %g]", n[0], n[1]);
}

// INI layout like the game's own config: [Group], Key=Value, the rest as an aligned ; comment.
void writer::cvars_ini(const std::wstring& path)
{
	static const char *types[] = { "Bool", "Int", "Float", "String" };
	auto& c = collector::get();

	// the shared /* */ banner, rewritten as ; comments
	std::string banner = header_comment("CVars.ini", "Config variables grouped like the game's ini sections. Each comment holds the type,\ndefault, allowed range and the RVA of the value the game reads, so \"witcher3.exe\"+RVA\nis the address to read or write (Byte for Bool, 4 Bytes for Int, Float for Float).");
	std::string s;
	size_t i = 0;
	while (i < banner.size())
	{
		size_t e = banner.find('\n', i);
		std::string line = banner.substr(i, e - i);
		i = e + 1;

		if (line == "/*" || line == "*/")
			continue;

		if (!line.empty() && line[0] == '*')
		{
			line[0] = ';';
		}

		s += line + "\n";
	}

	for (size_t k = 0; k < c.cvars.size();)
	{
		// one [Group] section, comments aligned inside it
		size_t e = k;
		size_t w = 0;
		while (e < c.cvars.size() && c.cvars[e].group == c.cvars[k].group)
		{
			w = std::max(w, std::min<size_t>(c.cvars[e].key.size() + 1 + c.cvars[e].value.size(), 64));
			++e;
		}

		s += "[" + c.cvars[k].group + "]\n";
		for (size_t j = k; j < e; ++j)
		{
			const cvar_info& v = c.cvars[j];
			std::string entry = v.key + "=" + v.value;
			std::string note = std::string(v.type < 4 ? types[v.type] : "?") + ", Default: " + (v.def.empty() ? "\"\"" : v.def);

			std::string r = range(v.validation);
			if (!r.empty())
			{
				note += ", Range: " + r;
			}

			// the value itself (what game code reads), else the object when the value lives on the heap
			note += v.value_rva ? ", RVA: " + hex(v.value_rva) : ", Object RVA: " + hex(v.rva);
			s += fmt("%-*s ; %s\n", (int)w, entry.c_str(), note.c_str());
		}

		s += "\n";
		k = e;
	}

	save(path, s);
}

static std::string json_str(const std::string& s)
{
	std::string r = "\"";
	for (char c : s)
	{
		if (c == '"' || c == '\\')
		{
			r.push_back('\\');
			r.push_back(c);
		}
		else if (c == '<')
		{
			r += "\\u003C"; // never close the <script> tag
		}
		else if ((unsigned char)c < 0x20)
		{
			r += fmt("\\u%04X", (unsigned char)c);
		}
		else
		{
			r.push_back(c);
		}
	}

	r.push_back('"');
	return r;
}

static std::string lower(std::string s)
{
	for (char& c : s)
	{
		c = (char)tolower((unsigned char)c);
	}

	return s;
}

// Every "exec function Name" in the game's script sources (content, dlc and mods), keyed by lowercase name,
// mapped to "relative/path.ws:line". Mods are scanned last so their definitions win.
static void scan_scripts(const std::wstring& dir, const std::wstring& root, std::unordered_map<std::string, std::string>& out)
{
	WIN32_FIND_DATAW fd;
	HANDLE h = FindFirstFileW((dir + L"\\*").c_str(), &fd);
	if (h == INVALID_HANDLE_VALUE)
		return;

	do
	{
		std::wstring name = fd.cFileName;
		if (name == L"." || name == L"..")
			continue;

		std::wstring full = dir + L"\\" + name;
		if (fd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY)
		{
			scan_scripts(full, root, out);
			continue;
		}

		if (name.size() < 3 || _wcsicmp(name.c_str() + name.size() - 3, L".ws") != 0)
			continue;

		FILE *f = nullptr;
		_wfopen_s(&f, full.c_str(), L"rb");
		if (!f)
			continue;

		std::string rel(full.begin() + root.size() + 1, full.end());
		for (char& c : rel)
		{
			c = c == '\\' ? '/' : c;
		}

		char line[1024];
		for (int n = 1; fgets(line, sizeof(line), f); ++n)
		{
			const char *p = line;
			while (*p == ' ' || *p == '\t')
			{
				++p;
			}

			if (strncmp(p, "exec", 4) != 0 || (p[4] != ' ' && p[4] != '\t'))
				continue;

			p += 4;
			while (*p == ' ' || *p == '\t')
			{
				++p;
			}

			if (strncmp(p, "function", 8) != 0)
				continue;

			p += 8;
			while (*p == ' ' || *p == '\t')
			{
				++p;
			}

			std::string id;
			while (isalnum((unsigned char)*p) || *p == '_')
			{
				id.push_back(*p++);
			}

			if (!id.empty())
			{
				// "content/content0/scripts/game/temp.ws" -> "game/temp.ws", mods keep their name: "modFoo: game/x.ws"
				std::string shown = rel;
				size_t at = rel.find("/scripts/");
				if (at != std::string::npos)
				{
					shown = rel.substr(at + 9);
					if (rel.compare(0, 5, "mods/") == 0)
					{
						shown = rel.substr(5, rel.find('/', 5) - 5) + ": " + shown;
					}
				}

				out[lower(id)] = shown + ":" + std::to_string(n);
			}
		}

		fclose(f);
	} while (FindNextFileW(h, &fd));

	FindClose(h);
}

