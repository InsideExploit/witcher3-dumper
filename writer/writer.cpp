static bool save(const std::wstring& path, const std::string& text)
{
	FILE *f = nullptr;
	_wfopen_s(&f, path.c_str(), L"wb");
	if (!f)
	{
		logger::get().info("cannot write %ls", path.c_str());
		return false;
	}

	fwrite(text.data(), 1, text.size(), f);
	fclose(f);
	return true;
}

static std::string fmt(const char *f, ...)
{
	va_list args;
	va_start(args, f);
	int n = vsnprintf(nullptr, 0, f, args);
	va_end(args);

	if (n <= 0)
		return "";

	std::string s(n, '\0');
	va_start(args, f);
	vsnprintf(s.data(), n + 1, f, args);
	va_end(args);
	return s;
}

static std::string hex(uint64_t v)
{
	return fmt("0x%llX", (unsigned long long)v);
}

static const char *repo = "https://github.com/InsideExploit/witcher3-dumper";

// "5.0.1048522 (P4CL 13413172)" from the exe's build banner
static std::string build()
{
	const std::string& v = anchors::get().version;
	if (v.empty())
		return "unknown";

	std::string s = v.substr(0, v.find(' '));
	size_t p = v.find("P4CL: ");
	if (p != std::string::npos)
	{
		s += " (P4CL " + v.substr(p + 6, v.find(' ', p + 6) - (p + 6)) + ")";
	}

	return s;
}

// banner at the top of every generated file; each line of 'about' becomes a line of the block
static std::string header_comment(const char *file, const std::string& about)
{
	std::string s = "/*\n* The Witcher 3 SDK\n*\n* Generated by witcher3-dumper\n* " + std::string(repo) + "\n*\n";
	s += "* Build: " + build() + "\n* File:  " + file + "\n";
	if (!about.empty())
	{
		s += "*\n";
		size_t i = 0;
		while (i < about.size())
		{
			size_t e = about.find('\n', i);
			if (e == std::string::npos)
			{
				e = about.size();
			}

			s += "* " + about.substr(i, e - i) + "\n";
			i = e + 1;
		}
	}

	s += "*/\n\n";
	return s;
}

static std::string flag_words(uint32_t f)
{
	static const std::pair<uint32_t, const char *> words[] = {
		{ FF_Private, "private" }, { FF_Protected, "protected" }, { FF_Native, "import" }, { FF_Final, "final" }, { FF_Latent, "latent" },
		{ FF_Entry, "entry" }, { FF_Exec, "exec" }, { FF_Timer, "timer" }, { FF_StoryScene, "storyscene" }, { FF_Quest, "quest" },
		{ FF_Cleanup, "cleanup" }, { FF_Reward, "reward" },
	};

	std::string s;
	for (auto& w : words)
	{
		if (f & w.first)
		{
			s += w.second;
			s += ' ';
		}
	}

	s += (f & FF_Event) ? "event " : "function ";
	return s;
}

// script style declaration: "import latent function Foo(a : int, optional b : string) : bool"
static std::string signature(const func_info& f)
{
	std::string s = flag_words(f.flags) + f.name + "(";
	for (size_t i = 0; i < f.params.size(); ++i)
	{
		const prop_info& p = f.params[i];
		if (i)
		{
			s += ", ";
		}

		if (p.flags & PF_Optional)
		{
			s += "optional ";
		}

		s += p.name + " : " + p.type;
	}

	s += ")";
	if (f.ret != "void")
	{
		s += " : " + f.ret;
	}

	return s;
}

static std::string ident(const std::string& s)
{
	static const std::unordered_set<std::string> keywords = {
		"alignas", "alignof", "and", "asm", "auto", "bool", "break", "case", "catch", "char", "class", "const", "continue", "default", "delete", "do",
		"double", "else", "enum", "explicit", "export", "extern", "false", "float", "for", "friend", "goto", "if", "inline", "int", "long", "mutable",
		"namespace", "new", "not", "operator", "or", "private", "protected", "public", "register", "return", "short", "signed", "sizeof", "static",
		"struct", "switch", "template", "this", "throw", "true", "try", "typedef", "typeid", "typename", "union", "unsigned", "using", "virtual",
		"void", "volatile", "while", "xor", "min", "max", "NULL", "TRUE", "FALSE", "IN", "OUT", "DELETE", "ERROR",
	};

	std::string r;
	for (char c : s)
	{
		bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_';
		r.push_back(ok ? c : '_');
	}

	if (r.empty() || (r[0] >= '0' && r[0] <= '9'))
	{
		r = "_" + r;
	}

	if (keywords.count(r))
	{
		r += "_";
	}

	return r;
}

